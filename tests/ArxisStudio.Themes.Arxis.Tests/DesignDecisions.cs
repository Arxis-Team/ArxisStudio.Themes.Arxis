namespace ArxisStudio.Themes.Arxis.Tests;

/// <summary>
/// Места, где тема намеренно расходится с дизайн-проектом.
/// </summary>
/// <remarks>
/// Список один на все сверки, и это не аккуратность, а необходимость. Проект
/// называет цвет дважды — семантическим токеном (<c>AxFg3</c>) в разделе
/// токенов и переменной (<c>fg3</c>) в картах состояний, — и сверяют его два
/// разных теста. Разойдись эти два списка, тема прошла бы одну сверку и
/// провалила другую, а причина у расхождения одна.
/// <para>
/// Расхождение заводят решением и с доводом. Проект — входные данные, а не
/// приговор: он рисовался по одному экрану и одной теме, и место, где он не
/// прав, лучше назвать вслух, чем молча возить неверный цвет.
/// </para>
/// </remarks>
internal static class DesignDecisions
{
    /// <summary>Цвет, который тема везёт вместо объявленного проектом.</summary>
    private static readonly Dictionary<(string Token, string Variant), string> Colours = new()
    {
        // Ссылка в светлой теме: таблица даёт #3574F0, но это 4,28:1 на белом —
        // ниже порога. Раздел 6 приёмки решает «взять AxBlue3 #3369D6 — 4,9:1»,
        // и макеты студии определяют свой --link ровно этим значением. Три
        // источника из четырёх сходятся против одной строки таблицы.
        [("AxLink", "Light")] = "#3369D6",

        // Третичный и выключенный текст поменялись ступенями шкалы Int UI, и
        // причина не в самом контрасте, а в перевёрнутом смысле. По таблице
        // третичный стоял на Gray7 в тёмной и на Gray8 в светлой, выключенный —
        // на Gray8 в обеих. В тёмной это значило, что выключенный текст
        // читается ЛУЧШЕ включённого второстепенного: 4,75:1 против 3,46:1 на
        // основном фоне. В светлой они были одним цветом, и отличить
        // «недоступно» от «доступно, но второстепенно» было нельзя ничем.
        //
        // Приглушение — признак недоступности, и приглушён обязан быть
        // выключенный. Обе ступени взяты с той же шкалы, ничего не выдумано, и
        // дальше двигать некуда: следующая ступень в обоих вариантах — это
        // AxFg2, и третичного текста не стало бы вовсе.
        [("AxFg3", "Dark")] = "#868A91",
        [("AxFg3", "Light")] = "#818594",
        [("AxFgDisabled", "Dark")] = "#6F737A",
    };

    /// <summary>
    /// Как переменная карты состояний называется среди токенов.
    /// </summary>
    /// <remarks>
    /// Только те, у кого расхождение есть: перечислять остальные значило бы
    /// заводить вторую таблицу имён и однажды её не обновить. <c>link</c> сюда
    /// не попал намеренно — ни одно состояние проекта им не красит.
    /// </remarks>
    private static readonly Dictionary<string, string> Tokens = new(StringComparer.Ordinal)
    {
        ["fg3"] = "AxFg3",
        ["fgDis"] = "AxFgDisabled",
    };

    /// <summary>Цвет семантического токена, каким его везёт тема.</summary>
    /// <param name="token">Имя токена: <c>AxFg3</c>.</param>
    /// <param name="variant">Вариант темы.</param>
    /// <param name="declared">Что объявил проект.</param>
    public static string Token(string token, string variant, string declared) =>
        Colours.GetValueOrDefault((token, variant), declared);

    /// <summary>Цвет переменной карты состояний, каким его везёт тема.</summary>
    /// <param name="variable">Имя переменной: <c>fg3</c>.</param>
    /// <param name="variant">Вариант темы.</param>
    /// <param name="declared">Что объявил проект.</param>
    public static string Variable(string variable, string variant, string declared) =>
        Tokens.TryGetValue(variable, out var token) ? Token(token, variant, declared) : declared;
}
