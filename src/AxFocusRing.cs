using Avalonia;
using Avalonia.Controls;

namespace ArxisStudio.Themes.Arxis;

/// <summary>Где стоит кольцо фокуса относительно контрола.</summary>
internal enum AxFocusRingPlacement
{
    /// <summary>
    /// Снаружи, вокруг контрола со своей рамкой.
    /// </summary>
    /// <remarks>
    /// Рамка контрола на фокусе сама красится цветом кольца и становится его первым пикселем, а
    /// снаружи добавляется второй. Кольцо в два поверх перекрашенной рамки давало бы три.
    /// </remarks>
    Outside,

    /// <summary>
    /// Вокруг строки с подписью: флажок, переключатель, ссылка, ползунок.
    /// </summary>
    /// <remarks>
    /// Своей рамки у такого контрола нет, и весь контур несёт кольцо: два пикселя на просвете в
    /// один от края. Вплотную кольцо слилось бы с залитой коробкой отмеченного флажка в пятно.
    /// </remarks>
    Row,

    /// <summary>
    /// Внутри: строка списка, дерева, вкладка, сегмент.
    /// </summary>
    /// <remarks>
    /// Такая строка занимает всю ширину хозяина, и вынесенное наружу кольцо срезал бы он сам — от
    /// кольца остались бы две вертикальные чёрточки по бокам.
    /// </remarks>
    Inside,
}

/// <summary>
/// Кольцо фокуса: одна часть шаблона на все контролы темы.
/// </summary>
/// <remarks>
/// Форм у кольца три, и до этой вехи каждая повторялась в своём шаблоне четырьмя атрибутами:
/// поле, скругление, толщина, кисть. Повторение это расходится молча — кольцо с толщиной строки и
/// скруглением кнопки выглядит не ошибкой, а чуть другим кольцом. Теперь форма называется одним
/// словом, а из чего она сложена, знает тема кольца.
/// <para>
/// Кольцо не ловит мышь и по умолчанию скрыто; показывает его стиль контрола по
/// <c>:focus-visible</c> — то есть после Tab и стрелок, а не после щелчка. И то и другое
/// объявлено темой кольца, а не конструктором: значение, поставленное в коде, сильнее стиля, и
/// кольцо, спрятанное конструктором, не показалось бы уже никогда.
/// </para>
/// </remarks>
internal sealed class AxFocusRing : Border
{
    /// <summary>Где стоит кольцо.</summary>
    public static readonly StyledProperty<AxFocusRingPlacement> PlacementProperty =
        AvaloniaProperty.Register<AxFocusRing, AxFocusRingPlacement>(nameof(Placement));

    /// <summary>Где стоит кольцо.</summary>
    public AxFocusRingPlacement Placement
    {
        get => GetValue(PlacementProperty);
        set => SetValue(PlacementProperty, value);
    }
}
